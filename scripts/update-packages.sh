#!/usr/bin/env bash
# Package-manager manifests for a release, generated from its SHA256SUMS.txt:
#
#   scripts/update-packages.sh [--version X.Y.Z] [--sums FILE] [--date YYYY-MM-DD]
#                              [--out DIR | --in-place] [--flatpak-tarball FILE] [--no-source]
#
# Writes, under DIR (default target/packages):
#   homebrew/cratetune.rb                         Homebrew cask (per-arch DMG + sha256)
#   scoop/cratetune.json                          Scoop manifest (portable zip, checkver, autoupdate)
#   aur/cratetune-bin/{PKGBUILD,.SRCINFO}         AUR, from the release tarball
#   aur/cratetune/{PKGBUILD,.SRCINFO}             AUR, built from the tag's source archive
#   flatpak/<flatpak id>.yml, .metainfo.xml, .desktop   Flatpak (repackages the release tarball)
#
# --in-place writes into packaging/ instead (review `git diff`, then commit), which is how
#   the copies in the repository are refreshed. The publish job of release.yml runs this
#   script and attaches the result to the release as <id>-<ver>-package-manifests.tar.gz.
# --sums defaults to the published release's SHA256SUMS.txt (downloaded with curl).
# --date is the release date for the AppStream metadata (default: the release's publish
#   date from `gh`, else today, UTC).
# --flatpak-tarball points the Flatpak manifest at a local tarball instead of the release
#   URL (CI builds the Flatpak from the artifact before anything is published).
# --no-source skips the source PKGBUILD (it downloads the tag's archive to hash it).
#
# Only bash, sed, curl and sha256sum / shasum are needed; it runs on macOS and Linux.
# Names and URLs come from packaging/app.env, like the other packaging scripts.
set -euo pipefail
source "$(dirname "$0")/lib/app-env.sh"
cd "$ROOT"

VERSION="$APP_VERSION" SUMS="" DATE="" OUT="target/packages" IN_PLACE=0 FLATPAK_TARBALL="" SOURCE=1
while [[ $# -gt 0 ]]; do
  case "$1" in
    --version) VERSION="${2#v}"; shift 2 ;;
    --sums) SUMS="$2"; shift 2 ;;
    --date) DATE="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --in-place) IN_PLACE=1; shift ;;
    --flatpak-tarball) FLATPAK_TARBALL="$2"; shift 2 ;;
    --no-source) SOURCE=0; shift ;;
    -h|--help) sed -n '2,25p' "$0"; exit 0 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] || { echo "bad version '$VERSION'" >&2; exit 2; }
[[ -n "$UPDATE_REPO" ]] || { echo "UPDATE_REPO is empty in packaging/app.env" >&2; exit 1; }

OWNER="${UPDATE_REPO%%/*}"
# The AppStream id (scripts/lib/app-env.sh), also the Flatpak's app id.
FLATPAK_ID="$APPSTREAM_ID"
REPO_URL="https://github.com/$UPDATE_REPO"
DOWNLOAD="$REPO_URL/releases/download/v$VERSION"
LICENSE_ID="GPL-3.0-only"
# The MPRIS bus name suffix (identity::dbus_name in the app: '-' and '.' → '_').
DBUS_NAME="${APP_ID//[-.]/_}"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

sha256() {
  if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

if [[ -z "$SUMS" ]]; then
  SUMS="$TMP/SHA256SUMS.txt"
  curl -fsSL -o "$SUMS" "$DOWNLOAD/SHA256SUMS.txt" ||
    { echo "couldn't download $DOWNLOAD/SHA256SUMS.txt (is v$VERSION published?)" >&2; exit 1; }
fi
[[ -r "$SUMS" ]] || { echo "can't read $SUMS" >&2; exit 1; }
# The sha256 of one asset, by its name's suffix after <id>-<version>.
sum_of() {
  local name="$APP_ID-$VERSION$1" hash
  hash="$(awk -v n="$name" '{ f = $2; sub(/^\*/, "", f); if (f == n) print $1 }' "$SUMS")"
  [[ "$hash" =~ ^[0-9a-f]{64}$ ]] || { echo "no sha256 for $name in $SUMS" >&2; exit 1; }
  echo "$hash"
}
SHA_DMG_ARM="$(sum_of -macos-arm64.dmg)"
SHA_DMG_INTEL="$(sum_of -macos-x86_64.dmg)"
SHA_ZIP_WIN="$(sum_of -windows-x64.zip)"
SHA_TAR_LINUX="$(sum_of -linux-x86_64.tar.gz)"

if [[ -z "$DATE" ]]; then
  DATE="$(gh release view "v$VERSION" -R "$UPDATE_REPO" --json publishedAt -q '.publishedAt' 2>/dev/null | cut -c1-10 || true)"
  [[ "$DATE" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]] || DATE="$(date -u +%Y-%m-%d)"
fi

if [[ $IN_PLACE == 1 ]]; then OUT="packaging"; fi
mkdir -p "$OUT/homebrew" "$OUT/scoop" "$OUT/aur/$APP_ID-bin" "$OUT/flatpak"
GENERATED="Generated by scripts/update-packages.sh for v$VERSION; edit the script, not this file."

# ---------------------------------------------------------------- Homebrew cask
cat > "$OUT/homebrew/$APP_ID.rb" <<RUBY
# $GENERATED
cask "$APP_ID" do
  arch arm: "arm64", intel: "x86_64"

  version "$VERSION"
  sha256 arm:   "$SHA_DMG_ARM",
         intel: "$SHA_DMG_INTEL"

  url "$REPO_URL/releases/download/v#{version}/$APP_ID-#{version}-macos-#{arch}.dmg"
  name "$APP_NAME"
  desc "$APP_SUMMARY"
  homepage "$REPO_URL"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on :macos

  app "$APP_NAME.app"

  # The app is not notarized (ad-hoc signed), so Gatekeeper would refuse to open the
  # downloaded copy. Homebrew verified the DMG's sha256 above; drop the quarantine flag.
  # $APP_NAME sees the Caskroom entry and leaves updates to \`brew upgrade\`.
  postflight_steps do
    run "/usr/bin/xattr",
        args:         ["-dr", "com.apple.quarantine", "{{appdir}}/$APP_NAME.app"],
        must_succeed: false
  end

  zap trash: [
    "~/Library/Application Support/$APP_ID",
    "~/Library/Caches/$APP_ID",
    "~/Library/HTTPStorages/$BUNDLE_ID",
    "~/Library/Preferences/$BUNDLE_ID.plist",
    "~/Library/Saved Application State/$BUNDLE_ID.savedState",
    "~/Library/WebKit/$BUNDLE_ID",
  ]

  caveats <<~EOS
    $APP_NAME is not notarized by Apple. This cask removes the quarantine flag after
    installing, so it opens without a Gatekeeper prompt. Updates come from Homebrew:
      brew upgrade --cask $APP_ID
    Sign-ins and API keys are kept in the login keychain (service "$APP_ID");
    \`brew uninstall --zap\` does not remove them (use Keychain Access).
  EOS
end
RUBY

# ---------------------------------------------------------------- Scoop
cat > "$OUT/scoop/$APP_ID.json" <<JSON
{
    "##": "$GENERATED",
    "version": "$VERSION",
    "description": "$APP_SUMMARY",
    "homepage": "$REPO_URL",
    "license": "$LICENSE_ID",
    "notes": "Updates come from Scoop: scoop update $APP_ID. Settings are kept in %APPDATA%\\\\$APP_ID.",
    "architecture": {
        "64bit": {
            "url": "$DOWNLOAD/$APP_ID-$VERSION-windows-x64.zip",
            "hash": "$SHA_ZIP_WIN"
        }
    },
    "bin": "$APP_ID.exe",
    "shortcuts": [
        [
            "$APP_ID.exe",
            "$APP_NAME"
        ]
    ],
    "post_install": "Set-Content -Path \"\$dir\\\\packaged\" -Value 'scoop' -NoNewline",
    "checkver": {
        "github": "$REPO_URL"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "$REPO_URL/releases/download/v\$version/$APP_ID-\$version-windows-x64.zip"
            }
        },
        "hash": {
            "url": "\$baseurl/SHA256SUMS.txt",
            "regex": "\$sha256\\\\s+\\\\*?\$basename"
        }
    }
}
JSON

# ---------------------------------------------------------------- AUR
# Libraries the binary loads: NEEDED (alsa, xcb, xkbcommon) plus what GPUI dlopens
# (Vulkan, Wayland, X11, fontconfig / freetype). D-Bus and TLS are pure Rust.
AUR_DEPENDS=(alsa-lib fontconfig freetype2 gcc-libs glibc hicolor-icon-theme libx11 libxcb
  libxkbcommon libxkbcommon-x11 vulkan-icd-loader wayland)
AUR_OPTDEPENDS=("vulkan-driver: GPU rendering (vulkan-radeon, vulkan-intel or nvidia-utils)"
  "org.freedesktop.secrets: keep sign-ins and API keys in the keyring (gnome-keyring, kwallet)")
MAINTAINER="# Maintainer: $OWNER <https://github.com/$OWNER>"

quote_array() { local out="" item; for item in "$@"; do out+="'$item' "; done; echo "${out% }"; }

# .SRCINFO the way `makepkg --printsrcinfo` prints it: pkgbase fields in makepkg's order,
# arch-specific ones after the generic ones, then the pkgname line.
write_srcinfo() { # file pkgname arch source sha [makedepends...] -- [depends...]
  local file="$1" name="$2" arch="$3" source="$4" sha="$5"; shift 5
  local makedeps=() deps=()
  while [[ $# -gt 0 && "$1" != "--" ]]; do makedeps+=("$1"); shift; done
  [[ $# -gt 0 ]] && shift
  deps=("$@")
  {
    echo "pkgbase = $name"
    printf '\tpkgdesc = %s\n' "$APP_SUMMARY"
    printf '\tpkgver = %s\n' "${VERSION//-/_}"
    printf '\tpkgrel = 1\n'
    printf '\turl = %s\n' "$REPO_URL"
    printf '\tarch = %s\n' "$arch"
    printf '\tlicense = %s\n' "$LICENSE_ID"
    local d
    for d in ${makedeps[@]+"${makedeps[@]}"}; do printf '\tmakedepends = %s\n' "$d"; done
    for d in "${deps[@]}"; do printf '\tdepends = %s\n' "$d"; done
    for d in "${AUR_OPTDEPENDS[@]}"; do printf '\toptdepends = %s\n' "$d"; done
    if [[ "$name" == *-bin ]]; then
      printf '\tprovides = %s\n' "$APP_ID"
      printf '\tconflicts = %s\n' "$APP_ID"
      printf '\toptions = !strip\n'
      printf '\toptions = !debug\n'
      printf '\tsource_%s = %s\n' "$arch" "$source"
      printf '\tsha256sums_%s = %s\n' "$arch" "$sha"
    else
      printf '\tsource = %s\n' "$source"
      printf '\tsha256sums = %s\n' "$sha"
    fi
    echo
    echo "pkgname = $name"
  } > "$file"
}

# The install for both: files under /usr plus the marker that tells the app pacman
# updates it (music_core::updater::PackageManager; the self-updater stays off).
PACKAGE_BODY="  install -Dm755 bin/$APP_ID \"\$pkgdir/usr/bin/$APP_ID\"
  install -Dm644 share/applications/$APP_ID.desktop -t \"\$pkgdir/usr/share/applications\"
  install -Dm644 share/metainfo/*.metainfo.xml -t \"\$pkgdir/usr/share/metainfo\"
  local icon
  for icon in share/icons/hicolor/*/apps/$APP_ID.png; do
    install -Dm644 \"\$icon\" \"\$pkgdir/usr/\$icon\"
  done
  install -Dm644 LICENSE \"\$pkgdir/usr/share/licenses/\$pkgname/LICENSE\"
  # Tells $APP_NAME that pacman updates it, so the in-app updater stays off.
  install -dm755 \"\$pkgdir/usr/share/$APP_ID\"
  printf 'aur\\n' > \"\$pkgdir/usr/share/$APP_ID/packaged\""

BIN_SOURCE="$APP_ID-bin-$VERSION.tar.gz::$DOWNLOAD/$APP_ID-$VERSION-linux-x86_64.tar.gz"
cat > "$OUT/aur/$APP_ID-bin/PKGBUILD" <<PKG
$MAINTAINER
# $GENERATED
pkgname=$APP_ID-bin
pkgver=${VERSION//-/_}
_tag=$VERSION
pkgrel=1
pkgdesc="$APP_SUMMARY"
arch=('x86_64')
url="$REPO_URL"
license=('$LICENSE_ID')
depends=($(quote_array "${AUR_DEPENDS[@]}"))
optdepends=($(quote_array "${AUR_OPTDEPENDS[@]}"))
provides=('$APP_ID')
conflicts=('$APP_ID')
options=('!strip' '!debug')
source_x86_64=("$APP_ID-bin-\$_tag.tar.gz::\$url/releases/download/v\$_tag/$APP_ID-\$_tag-linux-x86_64.tar.gz")
sha256sums_x86_64=('$SHA_TAR_LINUX')

package() {
  cd "$APP_ID-\$_tag-linux-x86_64"
$PACKAGE_BODY
}
PKG
write_srcinfo "$OUT/aur/$APP_ID-bin/.SRCINFO" "$APP_ID-bin" x86_64 "$BIN_SOURCE" "$SHA_TAR_LINUX" -- "${AUR_DEPENDS[@]}"

if [[ $SOURCE == 1 ]]; then
  mkdir -p "$OUT/aur/$APP_ID"
  SRC_URL="$REPO_URL/archive/refs/tags/v$VERSION.tar.gz"
  if curl -fsSL -o "$TMP/source.tar.gz" "$SRC_URL"; then
    SHA_SRC="$(sha256 "$TMP/source.tar.gz")"
  else
    echo "couldn't download $SRC_URL; skipping the source PKGBUILD (--no-source to silence)" >&2
    SHA_SRC=""
  fi
  if [[ -n "$SHA_SRC" ]]; then
    # GitHub names the archive's top folder <repo>-<tag without v>.
    REPO_NAME="${UPDATE_REPO#*/}"
    SRC_SOURCE="$APP_ID-$VERSION.tar.gz::$SRC_URL"
    SRC_MAKEDEPENDS=(cargo clang pkgconf)
    cat > "$OUT/aur/$APP_ID/PKGBUILD" <<PKG
$MAINTAINER
# $GENERATED
pkgname=$APP_ID
pkgver=${VERSION//-/_}
_tag=$VERSION
pkgrel=1
pkgdesc="$APP_SUMMARY"
arch=('x86_64')
url="$REPO_URL"
license=('$LICENSE_ID')
depends=($(quote_array "${AUR_DEPENDS[@]}"))
makedepends=($(quote_array "${SRC_MAKEDEPENDS[@]}"))
optdepends=($(quote_array "${AUR_OPTDEPENDS[@]}"))
source=("$APP_ID-\$_tag.tar.gz::\$url/archive/refs/tags/v\$_tag.tar.gz")
sha256sums=('$SHA_SRC')

prepare() {
  cd "$REPO_NAME-\$_tag"
  export RUSTUP_TOOLCHAIN=stable
  cargo fetch --locked --target "\$(rustc -vV | sed -n 's/host: //p')"
}

build() {
  cd "$REPO_NAME-\$_tag"
  export RUSTUP_TOOLCHAIN=stable
  export CARGO_TARGET_DIR=target
  cargo build --frozen --release -p music-gpui
  # The same tree as the release tarball (desktop file, icons, AppStream metadata).
  RELEASE_DATE="\$(date -u -d "@\${SOURCE_DATE_EPOCH:-\$(date +%s)}" +%Y-%m-%d)" \\
    scripts/bundle-linux.sh --no-build
}

package() {
  cd "$REPO_NAME-\$_tag/target/bundle/$APP_ID-\$_tag-linux-\$CARCH"
$PACKAGE_BODY
}
PKG
    write_srcinfo "$OUT/aur/$APP_ID/.SRCINFO" "$APP_ID" x86_64 "$SRC_SOURCE" "$SHA_SRC" \
      "${SRC_MAKEDEPENDS[@]}" -- "${AUR_DEPENDS[@]}"
  fi
fi

# ---------------------------------------------------------------- Flatpak
# AppStream metadata: the template the tarball's metainfo comes from, with the Flatpak id.
sed -e "s|@METAINFO_ID@|$FLATPAK_ID|g" -e "s|@DESKTOP_ID@|$FLATPAK_ID.desktop|g" \
  -e "s|@APP_NAME@|$APP_NAME|g" -e "s|@APP_SUMMARY@|$APP_SUMMARY|g" -e "s|@APP_ID@|$APP_ID|g" \
  -e "s|@UPDATE_REPO@|$UPDATE_REPO|g" -e "s|@APP_VERSION@|$VERSION|g" -e "s|@RELEASE_DATE@|$DATE|g" \
  packaging/linux/app.metainfo.xml.in |
  sed '/^<!--$/,/^-->$/d' > "$OUT/flatpak/$FLATPAK_ID.metainfo.xml"

# The desktop entry: packaging/linux/app.desktop.in with the Flatpak id as icon.
sed -e "s|@APP_NAME@|$APP_NAME|g" -e "s|@APP_SUMMARY@|$APP_SUMMARY|g" \
  -e "s|^Icon=@APP_ID@|Icon=$FLATPAK_ID|" -e "s|@APP_ID@|$APP_ID|g" \
  packaging/linux/app.desktop.in > "$OUT/flatpak/$FLATPAK_ID.desktop"

if [[ -n "$FLATPAK_TARBALL" ]]; then
  FLATPAK_SOURCE="      - type: archive
        path: $FLATPAK_TARBALL
        sha256: $(sha256 "$FLATPAK_TARBALL")"
else
  FLATPAK_SOURCE="      - type: archive
        url: $DOWNLOAD/$APP_ID-$VERSION-linux-x86_64.tar.gz
        sha256: $SHA_TAR_LINUX
        x-checker-data:
          type: json
          url: https://api.github.com/repos/$UPDATE_REPO/releases/latest
          version-query: '.tag_name | sub(\"^v\"; \"\")'
          url-query: '\"$REPO_URL/releases/download/v\" + \$version + \"/$APP_ID-\" + \$version + \"-linux-x86_64.tar.gz\"'"
fi

cat > "$OUT/flatpak/$FLATPAK_ID.yml" <<YAML
# $GENERATED
#
# Repackages the release's Linux tarball (the binary CI builds and tests on Ubuntu 22.04
# with the pinned Rust toolchain) instead of compiling: see docs/RELEASING.md, "Flatpak".
# Build and install locally:
#   flatpak-builder --user --install --force-clean build-dir $FLATPAK_ID.yml
app-id: $FLATPAK_ID
runtime: org.freedesktop.Platform
runtime-version: '25.08'
sdk: org.freedesktop.Sdk
command: $APP_ID

finish-args:
  - --share=network
  - --share=ipc
  # GPUI draws with Vulkan: Wayland first, X11 only where there is no Wayland.
  - --socket=wayland
  - --socket=fallback-x11
  - --device=dri
  # Playback, and the microphone for song recognition (PipeWire answers PulseAudio).
  - --socket=pulseaudio
  # Media keys and the desktop's media controls.
  - --own-name=org.mpris.MediaPlayer2.$DBUS_NAME
  # Sign-ins and API keys in the keyring (Secret Service).
  - --talk-name=org.freedesktop.secrets
  # Discord Rich Presence talks to the Discord app's IPC socket (native or Flatpak).
  - --filesystem=xdg-run/discord-ipc-0
  - --filesystem=xdg-run/app/com.discordapp.Discord:create
  # Exports and backups default to Downloads; other files go through the file chooser
  # portal. Local files are read from Music.
  - --filesystem=xdg-download
  - --filesystem=xdg-music:ro
  # Turns the in-app updater off: Flatpak updates the app (FLATPAK_ID says so too).
  - --env=$(tr 'a-z.-' 'A-Z__' <<<"$APP_ID")_PACKAGED=flatpak

modules:
  - name: $APP_ID
    buildsystem: simple
    only-arches:
      - x86_64
    build-commands:
      - install -Dm755 bin/$APP_ID /app/bin/$APP_ID
      - |
        for icon in share/icons/hicolor/*/apps/$APP_ID.png; do
          size="\$(basename "\$(dirname "\$(dirname "\$icon")")")"
          install -Dm644 "\$icon" "/app/share/icons/hicolor/\$size/apps/$FLATPAK_ID.png"
        done
      - install -Dm644 $FLATPAK_ID.desktop -t /app/share/applications
      - install -Dm644 $FLATPAK_ID.metainfo.xml -t /app/share/metainfo
      - install -Dm644 LICENSE -t /app/share/licenses/$FLATPAK_ID
    sources:
$FLATPAK_SOURCE
      - type: file
        path: $FLATPAK_ID.desktop
      - type: file
        path: $FLATPAK_ID.metainfo.xml
YAML

echo "v$VERSION manifests in $OUT/ (Flatpak id $FLATPAK_ID, release date $DATE):"
(cd "$OUT" && find homebrew scoop aur flatpak -type f | sort | sed 's/^/  /')
