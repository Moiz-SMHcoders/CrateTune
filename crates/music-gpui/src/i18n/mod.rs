/// Byte-wise `a < b` / `==` / `>` usable in `const fn`.
const fn compare(a: &str, b: &str) -> i8 {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    let mut i = 0;
    while i < a.len() && i < b.len() {
        if a[i] != b[i] {
            return if a[i] < b[i] { -1 } else { 1 };
        }
        i += 1;
    }
    if a.len() == b.len() {
        0
    } else if a.len() < b.len() {
        -1
    } else {
        1
    }
}

const fn find(keys: &[&str], name: &str) -> Option<usize> {
    let (mut lo, mut hi) = (0, keys.len());
    while lo < hi {
        let mid = (lo + hi) / 2;
        match compare(keys[mid], name) {
            0 => return Some(mid),
            c if c < 0 => lo = mid + 1,
            _ => hi = mid,
        }
    }
    None
}

/// A plain message (see [`t!`] / [`k!`]).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Key(u16);

impl Key {
    /// Panics — at compile time when used in a `const` — if `name` isn't in
    /// `locales/en/*.lang`.
    pub const fn new(name: &str) -> Key {
        match find(SIMPLE_KEYS, name) {
            Some(i) => Key(i as u16),
            None => panic!("unknown translation key: add it to crates/music-gpui/locales/en"),
        }
    }

    #[cfg(test)]
    pub fn name(self) -> &'static str {
        SIMPLE_KEYS[self.0 as usize]
    }

    /// Runtime lookup by name (script actions, tests).
    pub fn find(name: &str) -> Option<Key> {
        find(SIMPLE_KEYS, name).map(|i| Key(i as u16))
    }
}

/// A message with plural forms (see [`tp!`]).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct PluralKey(u16);

impl PluralKey {
    pub const fn new(name: &str) -> PluralKey {
        match find(PLURAL_KEYS, name) {
            Some(i) => PluralKey(i as u16),
            None => panic!(
                "unknown plural translation key: add `<key>.one` / `<key>.other` to crates/music-gpui/locales/en"
            ),
        }
    }
}

/// A UI language: an index into the embedded catalogs (`0` = English).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Locale(u8);

impl Locale {
    pub const ENGLISH: Locale = Locale(0);

    /// Every embedded locale, English first.
    pub fn all() -> impl Iterator<Item = Locale> {
        (0..CATALOGS.len()).map(|i| Locale(i as u8))
    }

    /// `de`, `pt-BR`, `zh-CN` (the catalog directory names).
    pub fn code(self) -> &'static str {
        CATALOGS[self.0 as usize].code
    }

    /// Exact catalog code, ignoring case and `_` vs `-`.
    pub fn from_code(code: &str) -> Option<Locale> {
        let code = code.replace('_', "-");
        Locale::all().find(|l| l.code().eq_ignore_ascii_case(&code))
    }

    /// The language's name in itself ("Deutsch"), from its own catalog.
    pub fn native_name(self) -> &'static str {
        const NAME: Key = Key::new("locale.native_name");
        lookup(self, NAME).unwrap_or(self.code())
    }

    /// The language's English name ("German"), for searching the picker.
    pub fn english_name(self) -> &'static str {
        Key::find(&format!("language.name.{}", self.code()))
            .and_then(|key| lookup(Locale::ENGLISH, key))
            .unwrap_or(self.code())
    }

    /// The plain language subtag (`pt` for `pt-BR`).
    pub fn language(self) -> &'static str {
        let code = self.code();
        code.split('-').next().unwrap_or(code)
    }

    #[cfg(test)]
    /// Share of English plain keys and plural groups this locale translates (0–100).
    pub fn coverage(self) -> f32 {
        let catalog = &CATALOGS[self.0 as usize];
        let simple = (0..SIMPLE_KEYS.len())
            .filter(|&i| catalog.simple[i] != catalog.simple[i + 1])
            .count();
        let plural = (0..PLURAL_KEYS.len())
            .filter(|&i| catalog.plural[i * 6 + 5] != catalog.plural[i * 6 + 6])
            .count();
        let total = SIMPLE_KEYS.len() + PLURAL_KEYS.len();
        100. * (simple + plural) as f32 / total.max(1) as f32
    }
}

static CURRENT: AtomicU8 = AtomicU8::new(0);
static GENERATION: AtomicU32 = AtomicU32::new(0);

/// The UI language now in use.
#[inline]
pub fn locale() -> Locale {
    #[cfg(test)]
    if let Some(l) = TEST_LOCALE.get() {
        return Locale(l);
    }
    Locale(CURRENT.load(Ordering::Relaxed))
}

// Tests run in parallel threads: a test's locale is its own.
#[cfg(test)]
thread_local! {
    static TEST_LOCALE: std::cell::Cell<Option<u8>> = const { std::cell::Cell::new(None) };
}

/// Switches the UI language (views pick it up when they next render).
pub fn set_locale(locale: Locale) {
    #[cfg(test)]
    {
        TEST_LOCALE.set(Some(locale.0));
        return;
    }
    #[allow(unreachable_code)]
    if CURRENT.swap(locale.0, Ordering::Relaxed) != locale.0 {
        GENERATION.fetch_add(1, Ordering::Relaxed);
    }
    // gpui-component's own few strings (input context menu, default placeholders)
    // exist in English, Italian, Brazilian Portuguese and Chinese.
    gpui_component::set_locale(match locale.code() {
        code @ ("it" | "pt-BR" | "zh-CN" | "zh-TW") => code,
        _ => "en",
    });
}

/// Changes whenever the locale does (for caches holding translated text).
#[inline]
pub fn generation() -> u32 {
    GENERATION.load(Ordering::Relaxed)
}

#[inline]
fn lookup(locale: Locale, key: Key) -> Option<&'static str> {
    let catalog = &CATALOGS[locale.0 as usize];
    let i = key.0 as usize;
    let (start, end) = (catalog.simple[i] as usize, catalog.simple[i + 1] as usize);
    (start != end).then(|| &catalog.text[start..end])
}

/// The message in the current locale (English if it isn't translated).
#[inline]
pub fn text(key: Key) -> &'static str {
    lookup(locale(), key)
        .or_else(|| lookup(Locale::ENGLISH, key))
        .unwrap_or("")
}

fn plural_form(locale: Locale, key: PluralKey, category: Category) -> Option<&'static str> {
    let catalog = &CATALOGS[locale.0 as usize];
    let i = key.0 as usize * 6 + category as usize;
    let (start, end) = (catalog.plural[i] as usize, catalog.plural[i + 1] as usize);
    (start != end).then(|| &catalog.text[start..end])
}

/// The form of `key` for `count` in the current locale: its CLDR category, else its
/// `other` form, else English.
pub fn plural_text(key: PluralKey, count: u64) -> &'static str {
    let locale = locale();
    let category = plural::category(locale.language(), count);
    plural_form(locale, key, category)
        .or_else(|| plural_form(locale, key, Category::Other))
        .or_else(|| {
            let english = plural::category("en", count);
            plural_form(Locale::ENGLISH, key, english)
        })
        .or_else(|| plural_form(Locale::ENGLISH, key, Category::Other))
        .unwrap_or("")
}

/// Fills `{name}` placeholders from `args`; `{{` / `}}` are literal braces, unknown
/// placeholders stay as they are.
pub fn fill(template: &str, args: &[(&str, &dyn Display)]) -> String {
    use std::fmt::Write as _;
    let mut out = String::with_capacity(template.len() + 16);
    let mut rest = template;
    while let Some(i) = rest.find(['{', '}']) {
        out.push_str(&rest[..i]);
        let brace = rest.as_bytes()[i];
        let after = &rest[i + 1..];
        if after.as_bytes().first() == Some(&brace) {
            out.push(brace as char);
            rest = &after[1..];
            continue;
        }
        if brace == b'{'
            && let Some(end) = after.find('}')
            && let Some((_, value)) = args.iter().find(|(name, _)| *name == &after[..end])
        {
            let _ = write!(out, "{value}");
            rest = &after[end + 1..];
            continue;
        }
        out.push(brace as char);
        rest = after;
    }
    out.push_str(rest);
    out
}

/// The English source text of `key` (search fallbacks, e.g. country names).
pub fn english(key: Key) -> &'static str {
    lookup(Locale::ENGLISH, key).unwrap_or("")
}

/// `t!` with arguments.
pub fn format(key: Key, args: &[(&str, &dyn Display)]) -> String {
    fill(text(key), args)
}

/// `tp!`: the plural form for `count`, with `{count}` (grouped digits) and `args`.
pub fn plural(key: PluralKey, count: u64, args: &[(&str, &dyn Display)]) -> String {
    let template = plural_text(key, count);
    let grouped = format::number(count);
    if args.is_empty() {
        return fill(template, &[("count", &grouped)]);
    }
    let mut all: Vec<(&str, &dyn Display)> = Vec::with_capacity(args.len() + 1);
    all.extend_from_slice(args);
    all.push(("count", &grouped));
    fill(template, &all)
}

