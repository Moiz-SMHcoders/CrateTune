//! UI translations: catalogs embedded at build time, looked up without allocating.
//!
//! The catalogs are `crates/music-gpui/locales/<locale>/*.lang` (format in
//! `i18n_parse.rs`); English (`en`) is the source and the fallback for anything a
//! locale leaves out. `build.rs` turns them into sorted key tables plus one text blob
//! per locale, so:
//!
//! * [`t!`] with a literal key is checked at compile time (an unknown key is a
//!   compile error: the key is resolved to an index in a `const`) and returns a
//!   `&'static str` — an atomic load, two array reads and a slice; safe to call every
//!   frame, and `SharedString::from(&'static str)` doesn't allocate either;
//! * `t!("key", name = value)` fills `{name}` placeholders (allocates a `String`);
//! * [`tp!`] picks the CLDR plural form for a count (`{count}` is the count with the
//!   locale's digit grouping);
//! * [`k!`] makes a [`Key`] in `const` items (tables such as the sidebar entries);
//!   [`text`] resolves it.
//!
//! The current locale is a process-wide atomic ([`set_locale`]); views re-render
//! after a change (`MusicApp::apply_language`). [`generation`] changes with it, for
//! the rare cache that stores translated text. Number / date / relative-time helpers
//! are in [`format`].

/// A translated message: `t!("nav.home")` → `&'static str`;
/// `t!("np.casting_to", device = name)` → `String`.
macro_rules! t {
    ($key:literal) => {
        $crate::i18n::text({
            const KEY: $crate::i18n::Key = $crate::i18n::Key::new($key);
            KEY
        })
    };
    ($key:literal, $($name:ident = $value:expr),+ $(,)?) => {
        $crate::i18n::format(
            {
                const KEY: $crate::i18n::Key = $crate::i18n::Key::new($key);
                KEY
            },
            &[$((stringify!($name), &$value as &dyn ::std::fmt::Display)),+],
        )
    };
}

/// A message with plural forms: `tp!("common.songs", n)` → "5 songs" (`String`);
/// more placeholders: `tp!("x", n, name = value)`.
macro_rules! tp {
    ($key:literal, $count:expr $(, $name:ident = $value:expr)* $(,)?) => {
        $crate::i18n::plural(
            {
                const KEY: $crate::i18n::PluralKey = $crate::i18n::PluralKey::new($key);
                KEY
            },
            ($count) as u64,
            &[$((stringify!($name), &$value as &dyn ::std::fmt::Display)),*],
        )
    };
}

/// A [`Key`] for `const` tables; resolve it with [`text`] when rendering.
macro_rules! k {
    ($key:literal) => {
        $crate::i18n::Key::new($key)
    };
}

