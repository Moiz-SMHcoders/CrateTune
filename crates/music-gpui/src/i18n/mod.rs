/// One embedded catalog (generated by `build.rs`).
pub(crate) struct Catalog {
    pub code: &'static str,
    pub text: &'static str,
    /// `SIMPLE_KEYS.len() + 1` offsets into `text`; an empty range = not translated.
    pub simple: &'static [u32],
    /// `PLURAL_KEYS.len() * 6 + 1` offsets: the [`Category`] forms of each group.
    pub plural: &'static [u32],
}

