//! Exposes `packaging/app.env` (the app's name and ids, see `identity.rs`) to the
//! code, and on Windows embeds the icon + version info (`packaging/windows/app.rc.in`).

use std::fmt::Write as _;
use std::path::Path;

#[path = "i18n_parse.rs"]
mod i18n_parse;

fn main() {
    let env_file = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packaging/app.env");
    println!("cargo:rerun-if-changed={}", env_file.display());
    let text = std::fs::read_to_string(&env_file).expect("packaging/app.env");
    let mut app_name = String::new();
    for key in [
        "APP_NAME",
        "APP_ID",
        "BUNDLE_ID",
        "APP_SUMMARY",
        "UPDATE_REPO",
        "RELAY_URL",
    ] {
        let value = text
            .lines()
            .map(str::trim)
            .filter(|l| !l.starts_with('#'))
            .find_map(|l| l.strip_prefix(key)?.strip_prefix('='))
            .unwrap_or_else(|| panic!("{key} missing in packaging/app.env"))
            .trim()
            .trim_matches('"');
        println!("cargo:rustc-env=MUSIC_{key}={value}");
        if key == "APP_NAME" {
            app_name = value.to_owned();
        }
    }
    i18n_catalogs(&app_name);

    #[cfg(windows)]
    windows_resources(&text);
}

/// Embeds `locales/<locale>/*.lang` (see `i18n_parse.rs`): sorted key tables plus, per
/// locale, one text blob with offsets, so a lookup at runtime is two array reads and a
/// slice (`src/i18n/mod.rs`). `{app}` is replaced with the app's name here.
fn i18n_catalogs(app_name: &str) {
    use i18n_parse::{CATEGORIES, locale_dirs, parse_dir};
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("locales");
    println!("cargo:rerun-if-changed={}", root.display());
    println!("cargo:rerun-if-changed=i18n_parse.rs");
    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let fail = |e: String| -> ! { panic!("translation catalogs: {e}") };
    let dirs = locale_dirs(&root).unwrap_or_else(|e| fail(e));
    let catalogs: Vec<_> = dirs
        .iter()
        .map(|(code, dir)| (code.clone(), parse_dir(dir).unwrap_or_else(|e| fail(e))))
        .collect();
    let english = &catalogs[0].1;
    for (group, forms) in &english.plural {
        if !forms.contains_key(&5) {
            fail(format!("en: plural group {group} has no `other` form"));
        }
    }
    let simple_keys: Vec<&String> = english.simple.keys().collect();
    let plural_keys: Vec<&String> = english.plural.keys().collect();
    let app = |s: &str| s.replace("{app}", app_name);

    let mut code = String::from("// @generated by build.rs from locales/*/*.lang\n");
    let list = |keys: &[&String]| {
        keys.iter()
            .map(|k| format!("{k:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    writeln!(
        code,
        "pub(crate) const SIMPLE_KEYS: &[&str] = &[{}];",
        list(&simple_keys)
    )
    .unwrap();
    writeln!(
        code,
        "pub(crate) const PLURAL_KEYS: &[&str] = &[{}];",
        list(&plural_keys)
    )
    .unwrap();
    code.push_str("pub(crate) static CATALOGS: &[Catalog] = &[\n");
    for (locale, parsed) in &catalogs {
        for key in parsed.simple.keys().chain(parsed.plural.keys()) {
            if !english.simple.contains_key(key) && !english.plural.contains_key(key) {
                println!("cargo:warning={locale}: {key} is not an English key (ignored)");
            }
        }
        let mut blob = String::new();
        let mut simple = vec![0u32];
        for key in &simple_keys {
            if let Some(v) = parsed.simple.get(*key) {
                blob.push_str(&app(v));
            }
            simple.push(blob.len() as u32);
        }
        let mut plural = vec![blob.len() as u32];
        for key in &plural_keys {
            let forms = parsed.plural.get(*key);
            for category in 0..CATEGORIES.len() {
                if let Some(v) = forms.and_then(|f| f.get(&category)) {
                    blob.push_str(&app(v));
                }
                plural.push(blob.len() as u32);
            }
        }
        let file = format!("i18n_{locale}.txt");
        std::fs::write(out_dir.join(&file), &blob).expect("writing a catalog blob");
        let nums = |v: &[u32]| v.iter().map(u32::to_string).collect::<Vec<_>>().join(",");
        writeln!(
            code,
            "    Catalog {{ code: {locale:?}, text: include_str!(concat!(env!(\"OUT_DIR\"), \"/{file}\")), simple: &[{}], plural: &[{}] }},",
            nums(&simple),
            nums(&plural)
        )
        .unwrap();
    }
    code.push_str("];\n");
    std::fs::write(out_dir.join("i18n_catalog.rs"), code).expect("writing i18n_catalog.rs");
}

/// Icon and version resource for the .exe (native Windows builds; GPUI embeds its own
/// manifest, so the .rc has none). The template's `@KEY@` placeholders are filled in
/// here, so no string macros have to survive rc.exe's command line.
#[cfg(windows)]
fn windows_resources(env_text: &str) {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packaging/windows");
    let template = dir.join("app.rc.in");
    let icon = dir.join("app.ico");
    println!("cargo:rerun-if-changed={}", template.display());
    println!("cargo:rerun-if-changed={}", icon.display());
    let get = |key: &str| {
        env_text
            .lines()
            .find_map(|l| l.trim().strip_prefix(key)?.strip_prefix('='))
            .unwrap_or("")
            .trim()
            .trim_matches('"')
            .replace('"', "'")
    };
    let version = env!("CARGO_PKG_VERSION");
    let mut parts = version
        .split(['.', '-'])
        .map(|p| p.parse::<u16>().unwrap_or(0))
        .chain(std::iter::repeat(0));
    let numeric = format!(
        "{},{},{},0",
        parts.next().unwrap(),
        parts.next().unwrap(),
        parts.next().unwrap()
    );
    let icon_path = std::fs::canonicalize(&icon)
        .expect("packaging/windows/app.ico")
        .display()
        .to_string()
        .trim_start_matches(r"\\?\")
        .replace('\\', "\\\\");
    let rc = std::fs::read_to_string(&template)
        .expect("packaging/windows/app.rc.in")
        .replace("@APP_NAME@", &get("APP_NAME"))
        .replace("@APP_ID@", &get("APP_ID"))
        .replace("@APP_SUMMARY@", &get("APP_SUMMARY"))
        .replace("@APP_VERSION@", version)
        .replace("@APP_VERSION_NUM@", &numeric)
        .replace("@ICON_PATH@", &icon_path);
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("app.rc");
    std::fs::write(&out, rc).expect("writing app.rc");
    embed_resource::compile(&out, embed_resource::NONE)
        .manifest_optional()
        .expect("embedding the Windows resources failed");
}
